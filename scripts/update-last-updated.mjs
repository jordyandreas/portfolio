import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = join(root, "src/config/last-updated.ts");

function getIsoDate() {
  try {
    const dirty = execSync("git status --porcelain", {
      cwd: root,
      encoding: "utf8",
    }).trim();

    if (dirty) {
      return new Date().toISOString().slice(0, 10);
    }

    const commitDate = execSync("git log -1 --format=%cs", {
      cwd: root,
      encoding: "utf8",
    }).trim();

    if (/^\d{4}-\d{2}-\d{2}$/.test(commitDate)) {
      return commitDate;
    }
  } catch {
    // Fall through to today's date when git is unavailable.
  }

  return new Date().toISOString().slice(0, 10);
}

const lastUpdated = getIsoDate();

const contents = `/** Auto-generated by scripts/update-last-updated.mjs during prebuild. Do not edit by hand. */
export const lastUpdated = "${lastUpdated}";
`;

writeFileSync(outputPath, contents, "utf8");
console.log(`Updated lastUpdated to ${lastUpdated}`);
